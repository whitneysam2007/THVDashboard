-- THV Donor Dashboard production schema for Supabase PostgreSQL.
-- This migration intentionally preserves the current field names and text IDs so
-- existing dashboard code and the one-time MySQL export can retain every relation.

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  "openId" text not null unique,
  name text,
  email text,
  "loginMethod" text,
  role text not null default 'user' check (role in ('user', 'admin')),
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  "lastSignedIn" timestamptz not null default now()
);

create table if not exists public.allowed_team_emails (
  email text primary key,
  display_name text not null,
  created_at timestamptz not null default now()
);

